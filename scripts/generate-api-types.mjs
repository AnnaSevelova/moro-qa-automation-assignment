// Generates TypeScript types for the todo backend's API from its OpenAPI description:
// starts the backend (or uses one already running), saves the description it publishes at /v3/api-docs
// and generates the types from it with openapi-typescript.
//
// Usage: npm run api:generate

import { spawn } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { setTimeout as sleep } from 'node:timers/promises';

import openapiTS, { astToString } from 'openapi-typescript';

const ROOT_DIR = path.resolve(import.meta.dirname, '..');
const OUTPUT_DIR = path.join(ROOT_DIR, 'tests', 'api', 'generated');
const DOCS_URL = `${process.env.API_BASE_URL ?? 'http://localhost:8080'}/v3/api-docs`;

const HEADER = `/**
 * Generated by \`npm run api:generate\` from openapi.json, the OpenAPI description the todo backend
 * publishes at /v3/api-docs. Do not edit, regenerate instead.
 */

`;

async function fetchDocs() {
    try {
        const response = await fetch(DOCS_URL);

        return response.ok ? await response.json() : undefined;
    } catch {
        return undefined;
    }
}

/** Starts the backend and waits until it publishes its API description; returns it and a way to stop it. */
async function startBackend() {
    // Its own process group, so stopping it also stops the node process npm starts
    const backend = spawn('npm', ['run', 'api:start'], { cwd: ROOT_DIR, stdio: 'ignore', detached: true });
    const stop = () => process.kill(-backend.pid);

    for (let attempt = 0; attempt < 60; attempt++) {
        await sleep(500);
        const docs = await fetchDocs();

        if (docs) {
            return { docs, stop };
        }
    }

    stop();
    throw new Error(`The backend did not publish its API description at ${DOCS_URL} within 30 seconds`);
}

// A backend that is already running is used as it is and left running
const running = await fetchDocs();
const { docs, stop } = running ? { docs: running, stop: undefined } : await startBackend();

try {
    await mkdir(OUTPUT_DIR, { recursive: true });
    await writeFile(path.join(OUTPUT_DIR, 'openapi.json'), `${JSON.stringify(docs, null, 2)}\n`);
    await writeFile(path.join(OUTPUT_DIR, 'openapi-types.ts'), HEADER + astToString(await openapiTS(docs)));
    process.stdout.write(`API types generated from ${DOCS_URL} into ${path.relative(ROOT_DIR, OUTPUT_DIR)}/\n`);
} finally {
    stop?.();
}
